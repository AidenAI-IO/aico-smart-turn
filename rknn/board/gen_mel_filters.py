"""Generate whisper_mel_filters.h: the 80 Slaney mel filters Whisper uses.

The table comes straight from WhisperFeatureExtractor, so the C feature code
uses exactly the same weights. Each filter is stored sparsely as
(first FFT bin, bin count, offset into kMelWeights).

    python rknn/board/gen_mel_filters.py > rknn/board/whisper_mel_filters.h
"""

import numpy as np
from transformers import WhisperFeatureExtractor


def main():
    filters = WhisperFeatureExtractor().mel_filters.T.astype(np.float32)  # (80 mel, 201 bins)
    starts, counts, offsets, weights = [], [], [], []
    for row in filters:
        nonzero = np.flatnonzero(row)
        first, last = (int(nonzero[0]), int(nonzero[-1])) if len(nonzero) else (0, -1)
        starts.append(first)
        counts.append(last - first + 1)
        offsets.append(len(weights))
        weights.extend(row[first:last + 1].tolist())

    print("/* Generated by gen_mel_filters.py from transformers' WhisperFeatureExtractor. Do not edit. */")
    print("#ifndef WHISPER_MEL_FILTERS_H")
    print("#define WHISPER_MEL_FILTERS_H")
    print()
    print(f"#define WHISPER_N_MELS {filters.shape[0]}")
    print(f"#define WHISPER_N_FREQS {filters.shape[1]}")
    print()
    for name, values in (("kMelStart", starts), ("kMelCount", counts), ("kMelOffset", offsets)):
        print(f"static const unsigned short {name}[WHISPER_N_MELS] = {{")
        for i in range(0, len(values), 16):
            print("    " + ", ".join(str(v) for v in values[i:i + 16]) + ",")
        print("};")
    print(f"static const float kMelWeights[{len(weights)}] = {{")
    for i in range(0, len(weights), 6):
        print("    " + ", ".join(f"{w:.9e}f" for w in weights[i:i + 6]) + ",")
    print("};")
    print()
    print("#endif")


if __name__ == "__main__":
    main()
